import sharp, { Metadata, Sharp } from 'sharp';
import { ImageProcessor, ProcessedImage, ProcessedVariant } from '../domain/image-processor';
import { MediaError } from '../domain/media-errors';
import {
  DISPLAY_PX,
  ImageVariant,
  MAX_DIMENSION_PX,
  THUMB_PX,
  assertDimensions,
  assertSupportedFormat,
  assertUploadSize,
} from '../domain/media-rules';

/** sharp's output metadata for one generated variant. */
interface VariantOut {
  readonly bytes: Uint8Array;
  readonly widthPx: number;
  readonly heightPx: number;
  readonly byteSize: number;
}

/**
 * sharp image processor (IP-5 Step 6, J10/J11; spec 7, 8.6.9). Decodes the actual bytes
 * (client filenames and MIME headers are never consulted), rejects anything outside the
 * approved raster set, enforces the decoded-dimension cap, auto-orients from EXIF and
 * strips all metadata, then renders the three approved WebP variants. Variant
 * dimensions are read back from the generated bytes so what we persist is what we
 * stored. smaller-than-target images are never upscaled (withoutEnlargement).
 *
 * Resource bounds (8.6.9): limitInputPixels caps decompression of crafted bombs at the
 * approved 4000x4000 surface, and the intake cap runs before decode. sharp's own
 * pipeline keeps peak memory proportional to the bounded input.
 */
export class SharpImageProcessor implements ImageProcessor {
  async process(input: Uint8Array): Promise<ProcessedImage> {
    assertUploadSize(input.byteLength);
    const base = sharp(Buffer.from(input), {
      limitInputPixels: MAX_DIMENSION_PX * MAX_DIMENSION_PX,
      failOn: 'error',
    });
    let meta: Metadata;
    try {
      meta = await base.metadata();
    } catch {
      // Malformed or disguised content (8.6.9): decode failure is a client error.
      throw new MediaError('INVALID_IMAGE');
    }
    assertSupportedFormat(meta.format);
    if (meta.width === undefined || meta.height === undefined)
      throw new MediaError('INVALID_IMAGE');
    // EXIF orientations 5-8 swap the axes; the cap applies to the displayed size.
    const swaps = meta.orientation !== undefined && meta.orientation >= 5;
    const widthPx = swaps ? meta.height : meta.width;
    const heightPx = swaps ? meta.width : meta.height;
    assertDimensions(widthPx, heightPx);

    // rotate() with no arguments auto-orients from EXIF and removes the tag; sharp
    // re-encodes without metadata by default, so EXIF and other tags are stripped.
    const oriented = base.rotate();
    const [original, display, thumb] = await Promise.all([
      this.render(oriented.clone().webp({ quality: 90 })),
      this.render(
        oriented
          .clone()
          .resize({
            width: DISPLAY_PX,
            height: DISPLAY_PX,
            fit: 'inside',
            withoutEnlargement: true,
          })
          .webp({ quality: 85 }),
      ),
      this.render(
        oriented
          .clone()
          .resize({
            width: THUMB_PX,
            height: THUMB_PX,
            fit: 'inside',
            withoutEnlargement: true,
          })
          .webp({ quality: 80 }),
      ),
    ]);
    const variant = (v: VariantOut): ProcessedVariant => ({
      key: '', // assigned by the service when the object keys are generated
      widthPx: v.widthPx,
      heightPx: v.heightPx,
      byteSize: v.byteSize,
      bytes: v.bytes,
    });
    const variants: Record<ImageVariant, ProcessedVariant> = {
      original: variant(original),
      thumb: variant(thumb),
      display: variant(display),
    };
    return { widthPx, heightPx, variants };
  }

  /** Encodes one variant and reads the stored dimensions back from the result. */
  private async render(pipeline: Sharp): Promise<VariantOut> {
    let out: Buffer;
    try {
      out = await pipeline.toBuffer();
    } catch {
      throw new MediaError('INVALID_IMAGE');
    }
    const meta = await sharp(out).metadata();
    if (
      meta.format !== 'webp' ||
      meta.width === undefined ||
      meta.height === undefined ||
      meta.orientation !== undefined
    )
      throw new MediaError('INVALID_IMAGE');
    return {
      bytes: new Uint8Array(out),
      widthPx: meta.width,
      heightPx: meta.height,
      byteSize: out.byteLength,
    };
  }
}
